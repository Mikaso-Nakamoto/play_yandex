const DICTS = { ru: RU, en: EN, tr: TR };
let lang = 'ru';
let dict = RU;

/** Сопоставление кода языка платформы с поддерживаемыми языками */
export function mapLang(code) {
  const c = String(code || '').toLowerCase().slice(0, 2);
  if (c === 'tr' || c === 'az') return 'tr';
  if (['ru', 'be', 'kk', 'uk', 'uz', 'ky', 'tg', 'tt', 'hy', 'ka', 'ba', 'cv'].includes(c)) return 'ru';
  if (!c) return 'ru';
  return 'en';
}

export function setLang(code) {
  lang = DICTS[code] ? code : mapLang(code);
  dict = DICTS[lang];
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export const getLang = () => lang;

function pluralRu(n, forms) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}

export function kittensWord(n) {
  if (lang === 'ru') return pluralRu(n, ['котёнка', 'котят', 'котят']);
  if (lang === 'en') return n === 1 ? 'kitten' : 'kittens';
  return '';
}

export function t(key, vars) {
  let s = dict[key];
  if (s === undefined) s = EN[key] !== undefined ? EN[key] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
  return s;
}

export function fmt(n) {
  const s = String(Math.floor(n));
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, '\u202f');
}
